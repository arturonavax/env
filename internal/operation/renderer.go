func renderPOSIXOp(op Operation, opts RenderOptions) (string, error) {
	switch op.Kind {
	case OpEnsureDirectory:
		return fmt.Sprintf("mkdir -p %s", EscapePOSIX(op.TargetPath)), nil

	case OpCopyAtomic:
		return fmt.Sprintf("cp -p %s %s", EscapePOSIX(op.SourcePath), EscapePOSIX(op.TargetPath)), nil

	case OpDeleteOwned:
		return fmt.Sprintf("rm -f %s", EscapePOSIX(op.TargetPath)), nil

	case OpCreateSymlinkOwned:
		return fmt.Sprintf("ln -sf %s %s", EscapePOSIX(op.SourcePath), EscapePOSIX(op.TargetPath)), nil

	case OpWriteAtomic:
		encoded := base64.StdEncoding.EncodeToString([]byte(op.Content))
		return fmt.Sprintf("echo %s | base64 -d > %s", EscapePOSIX(encoded), EscapePOSIX(op.TargetPath)), nil

	case OpExecArgv, OpPackageInstall, OpPackageRemove, OpPackageUpgrade:
		if len(op.Argv) == 0 {
			return "", fmt.Errorf("operation %s has empty argv", op.OpID)
		}
		parts := make([]string, len(op.Argv))
		for i, a := range op.Argv {
			parts[i] = EscapePOSIX(a)
		}
		return strings.Join(parts, " "), nil

	case OpAnxRuntimeDelegation:
		if opts.Standalone {
			return "", &UnsupportedOperationError{
				OpID:   op.OpID,
				Kind:   op.Kind,
				Target: "sh",
				Reason: "cannot delegate to ANX runtime in standalone script mode",
			}
		}
		if len(op.Argv) > 0 {
			parts := make([]string, len(op.Argv))
			for i, a := range op.Argv {
				parts[i] = EscapePOSIX(a)
			}
			return strings.Join(parts, " "), nil
		}
		return fmt.Sprintf("anx apply --requested %s", EscapePOSIX(op.TargetPath)), nil

	default:
		return "", fmt.Errorf("unhandled op kind: %s", op.Kind)
	}
}

func renderPowerShellOp(op Operation, opts RenderOptions) (string, error) {
	switch op.Kind {
	case OpEnsureDirectory:
		return fmt.Sprintf("New-Item -ItemType Directory -Force -Path %s | Out-Null", EscapePowerShell(op.TargetPath)), nil

	case OpCopyAtomic:
		return fmt.Sprintf("Copy-Item -Force -Path %s -Destination %s", EscapePowerShell(op.SourcePath), EscapePowerShell(op.TargetPath)), nil

	case OpDeleteOwned:
		return fmt.Sprintf("Remove-Item -Force -ErrorAction SilentlyContinue -Path %s", EscapePowerShell(op.TargetPath)), nil

	case OpCreateSymlinkOwned:
		return fmt.Sprintf("New-Item -ItemType SymbolicLink -Force -Path %s -Target %s | Out-Null", EscapePowerShell(op.TargetPath), EscapePowerShell(op.SourcePath)), nil

	case OpWriteAtomic:
		encoded := base64.StdEncoding.EncodeToString([]byte(op.Content))
		return fmt.Sprintf("[System.IO.File]::WriteAllBytes(%s, [System.Convert]::FromBase64String(%s))",
			EscapePowerShell(op.TargetPath),
			EscapePowerShell(encoded),
		), nil

	case OpExecArgv, OpPackageInstall, OpPackageRemove:
		if len(op.Argv) == 0 {
			return "", fmt.Errorf("operation %s has empty argv", op.OpID)
		}
		parts := make([]string, len(op.Argv))
		for i, a := range op.Argv {
			parts[i] = EscapePowerShell(a)
		}
		return "& " + strings.Join(parts, " "), nil

	case OpAnxRuntimeDelegation:
		if opts.Standalone {
			return "", &UnsupportedOperationError{
				OpID:   op.OpID,
				Kind:   op.Kind,
				Target: "powershell",
				Reason: "cannot delegate to ANX runtime in standalone script mode",
			}
		}
		return fmt.Sprintf("& anx apply --requested %s", EscapePowerShell(op.TargetPath)), nil

	default:
		return "", fmt.Errorf("unhandled op kind: %s", op.Kind)
	}
}
