// Install generates user systemd units on Linux or a launchd plist on macOS and enables scheduled wakeups.
func (m *Manager) Install(ctx context.Context) (*InstallResult, error) {
	binDir := filepath.Dir(m.binaryPath)

	if m.plat.OS() == "darwin" {
		dir := m.LaunchAgentsDir()
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return nil, fmt.Errorf("creating LaunchAgents directory: %w", err)
		}
		hour, minute := parseHHMM(m.cfg.Daemon.AutoWake.Time)
		plistPath := filepath.Join(dir, LaunchdLabel+".plist")
		plistContent := fmt.Sprintf(`<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>%s</string>
  <key>ProgramArguments</key>
  <array>
    <string>%s</string>
    <string>ai</string>
    <string>daemon</string>
    <string>run-wake-cycle</string>
  </array>
  <key>StartCalendarInterval</key>
  <dict>
    <key>Hour</key>
    <integer>%d</integer>
    <key>Minute</key>
    <integer>%d</integer>
  </dict>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key>
    <string>%s:/usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin</string>
  </dict>
</dict>
</plist>
`, LaunchdLabel, m.binaryPath, hour, minute, binDir)

		if err := os.WriteFile(plistPath, []byte(plistContent), 0o644); err != nil {
			return nil, fmt.Errorf("writing launchd plist: %w", err)
		}
		if _, err := m.lookPath("launchctl"); err == nil {
			_, _ = m.exec.RunWithInput(ctx, security.RunOptions{}, "launchctl", "load", "-w", plistPath)
		}
		return &InstallResult{Files: []string{plistPath}}, nil
	}

	dir := m.SystemdUserDir()
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, fmt.Errorf("creating systemd user directory: %w", err)
	}

	wakeTime := m.cfg.Daemon.AutoWake.Time
	if wakeTime == "" {
		wakeTime = "04:00"
	}

	monitorUnit := fmt.Sprintf(`[Unit]
Description=ANX AI Quota & D-Bus Sleep/Resume Monitor
After=graphical-session.target network.target

[Service]
Type=simple
ExecStart=%s ai daemon run-monitor
Restart=always
RestartSec=10
Environment=PATH=%s:/usr/local/bin:/usr/bin:/bin
Environment=DISPLAY=:0

[Install]
WantedBy=default.target
`, m.binaryPath, binDir)

	wakeupService := fmt.Sprintf(`[Unit]
Description=ANX Scheduled AI Quota Wakeup & Rolling Refresh
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=%s ai daemon run-wake-cycle
Environment=PATH=%s:/usr/local/bin:/usr/bin:/bin
`, m.binaryPath, binDir)

	wakeupTimer := fmt.Sprintf(`[Unit]
Description=ANX Daily %s AI Quota Wakeup Timer

[Timer]
OnCalendar=*-*-* %s:00
Persistent=true

[Install]
WantedBy=timers.target
`, wakeTime, wakeTime)

	// Clean up legacy unit names if present
	if _, err := m.lookPath("systemctl"); err == nil {
		legacyUnits := []string{
			"aitools-monitor.service",
			"aitools-wakeup.service",
			"aitools-wakeup.timer",
			"aitools-wake.service",
			"aitools-wake.timer",
			"quota-monitor.service",
			"quota-primer.service",
			"quota-primer.timer",
		}
		for _, leg := range legacyUnits {
			_, _ = m.exec.RunWithInput(ctx, security.RunOptions{}, "systemctl", "--user", "stop", leg)
			_, _ = m.exec.RunWithInput(ctx, security.RunOptions{}, "systemctl", "--user", "disable", leg)
			_ = os.Remove(filepath.Join(dir, leg))
		}
	}

	files := map[string]string{
		filepath.Join(dir, UnitMonitorService): monitorUnit,
		filepath.Join(dir, UnitWakeupService):  wakeupService,
		filepath.Join(dir, UnitWakeupTimer):    wakeupTimer,
	}

	created := make([]string, 0, len(files))
	for p, content := range files {
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			return nil, fmt.Errorf("writing unit %q: %w", p, err)
		}
		created = append(created, p)
	}

	if _, err := m.lookPath("systemctl"); err == nil {
		_, _ = m.exec.RunWithInput(ctx, security.RunOptions{}, "systemctl", "--user", "daemon-reload")
		_, _ = m.exec.RunWithInput(ctx, security.RunOptions{}, "systemctl", "--user", "enable", "--now", UnitMonitorService)
		_, _ = m.exec.RunWithInput(ctx, security.RunOptions{}, "systemctl", "--user", "enable", "--now", UnitWakeupTimer)
	}

	if m.cfg.Daemon.AutoWake.Enabled {
		_, _, _ = m.ScheduleNextRTC(ctx, wakeTime)
	}

	return &InstallResult{Files: created}, nil
}

// Uninstall disables and removes installed systemd units or launchd plist files and disarms RTC wakeups.
func (m *Manager) Uninstall(ctx context.Context) error {
	if m.plat.OS() == "darwin" {
		plistPath := filepath.Join(m.LaunchAgentsDir(), LaunchdLabel+".plist")
		if _, err := m.lookPath("launchctl"); err == nil {
			_, _ = m.exec.RunWithInput(ctx, security.RunOptions{}, "launchctl", "unload", plistPath)
		}
		if err := os.Remove(plistPath); err != nil && !errors.Is(err, os.ErrNotExist) {
			return err
		}
		return nil
	}

	legacyUnits := []string{
		UnitMonitorService,
		UnitWakeupService,
		UnitWakeupTimer,
		"aitools-monitor.service",
		"aitools-wakeup.service",
		"aitools-wakeup.timer",
		"aitools-wake.service",
		"aitools-wake.timer",
		"quota-monitor.service",
		"quota-primer.service",
		"quota-primer.timer",
	}

	if _, err := m.lookPath("systemctl"); err == nil {
		for _, u := range legacyUnits {
			_, _ = m.exec.RunWithInput(ctx, security.RunOptions{}, "systemctl", "--user", "stop", u)
			_, _ = m.exec.RunWithInput(ctx, security.RunOptions{}, "systemctl", "--user", "disable", u)
		}
	}

	dir := m.SystemdUserDir()
	for _, name := range legacyUnits {
		p := filepath.Join(dir, name)
		_ = os.Remove(p)
	}

	if _, err := m.lookPath("systemctl"); err == nil {
		_, _ = m.exec.RunWithInput(ctx, security.RunOptions{}, "systemctl", "--user", "daemon-reload")
	}

	_ = m.DisableRTC(ctx)
	return nil
}

// SetAutoWake toggles hardware RTC auto-wake in config.json and state.json, arming or disarming rtcwake.
func (m *Manager) SetAutoWake(ctx context.Context, enabled bool) error {
	m.cfg.Daemon.AutoWake.Enabled = enabled
	if err := config.SaveConfig(m.configPath, m.cfg); err != nil {
		return fmt.Errorf("saving config: %w", err)
	}

	st, err := m.store.Load()
	if err != nil {
		return err
	}
	st.AutoWakeEnabled = &enabled
	if !enabled {
		st.ExpectingAutoWake = false
		st.ScheduledWakeEpoch = 0
	}
	if err := m.store.Save(st); err != nil {
		return err
	}

	if enabled {
		_, _, _ = m.ScheduleNextRTC(ctx, m.cfg.Daemon.AutoWake.Time)
	} else {
		_ = m.DisableRTC(ctx)
	}
	return nil
}

// ScheduleNextRTC computes the next occurrence of wakeTimeHHMM, records it in state.json, and arms rtcwake when present.
func (m *Manager) ScheduleNextRTC(ctx context.Context, wakeTimeHHMM string) (time.Time, bool, error) {
	h, min := parseHHMM(wakeTimeHHMM)
	now := m.nowFunc()
	target := time.Date(now.Year(), now.Month(), now.Day(), h, min, 0, 0, now.Location())
	if !target.After(now) {
		target = target.Add(24 * time.Hour)
	}

	st, err := m.store.Load()
	if err != nil {
		return target, false, err
	}
	st.ScheduledWakeEpoch = target.Unix()
	st.ExpectingAutoWake = true
	if err := m.store.Save(st); err != nil {
		return target, false, err
	}

	if _, lookErr := m.lookPath("rtcwake"); lookErr != nil {
		return target, false, nil
	}

	_, runErr := m.exec.RunWithInput(
		ctx,
		security.RunOptions{Timeout: 10 * time.Second},
		"sudo",
		"-n",
		"rtcwake",
		"-m",
		"no",
		"-u",
		"-t",
		strconv.FormatInt(target.Unix(), 10),
	)
	if runErr != nil {
		// Attempt direct sysfs write or sudo tee
		alarmPath := "/sys/class/rtc/rtc0/wakealarm"
		if _, statErr := os.Stat(alarmPath); statErr == nil {
			_ = os.WriteFile(alarmPath, []byte("0\n"), 0o644)
			if writeErr := os.WriteFile(alarmPath, []byte(strconv.FormatInt(target.Unix(), 10)+"\n"), 0o644); writeErr == nil {
				_ = m.store.AppendLog("INFO", "RTC_SYSFS_ARMED", fmt.Sprintf("Armed RTC via sysfs to %d", target.Unix()), nil)
				return target, true, nil
			}
			cmd := fmt.Sprintf("echo 0 > %s && echo %d > %s", alarmPath, target.Unix(), alarmPath)
			if _, sysErr := m.exec.RunWithInput(ctx, security.RunOptions{Timeout: 5 * time.Second}, "sudo", "-n", "sh", "-c", cmd); sysErr == nil {
				_ = m.store.AppendLog("INFO", "RTC_SYSFS_ARMED", fmt.Sprintf("Armed RTC via sudo sysfs to %d", target.Unix()), nil)
				return target, true, nil
			}
		}
		_ = m.store.AppendLog("WARN", "RTC_SCHEDULE_FAILED", fmt.Sprintf("Failed to arm rtcwake: %v", runErr), nil)
		return target, false, runErr
	}
	_ = m.store.AppendLog("INFO", "RTC_ARMED", fmt.Sprintf("Armed rtcwake to %s (epoch %d)", target.Format(time.RFC3339), target.Unix()), nil)
	return target, true, nil
}

// DisableRTC clears scheduled wake flags in state.json and runs rtcwake -m disable if available.
func (m *Manager) DisableRTC(ctx context.Context) error {
	st, err := m.store.Load()
	if err != nil {
		return err
	}
	st.ExpectingAutoWake = false
	st.ScheduledWakeEpoch = 0
	if err := m.store.Save(st); err != nil {
		return err
	}

	if _, lookErr := m.lookPath("rtcwake"); lookErr == nil {
		_, _ = m.exec.RunWithInput(ctx, security.RunOptions{Timeout: 10 * time.Second}, "sudo", "-n", "rtcwake", "-m", "disable")
	}
	return nil
}

// Status inspects daemon configuration, state, hardware RTC alarm, systemd/launchd activity, and audit logs.
func (m *Manager) Status(ctx context.Context) (*StatusReport, error) {
	st, err := m.store.Load()
	if err != nil {
		return nil, err
	}

	aw := m.cfg.Daemon.AutoWake
	rep := &StatusReport{
		AutoWakeEnabled:      aw.Enabled,
		TargetWakeTime:       aw.Time,
		AutoResuspend:        aw.AutoResuspend,
		ResuspendDelaySec:    aw.ResuspendDelaySec,
		HardwareRTCAlarm:     "none (disarmed)",
		MonitorServiceStatus: "inactive",
		WakeupTimerStatus:    "inactive",
		AuditLogPath:         m.store.LogFilePath(),
	}
	if st.ScheduledWakeEpoch > 0 {
		rep.NextScheduledWake = time.Unix(st.ScheduledWakeEpoch, 0)
	}

	if data, readErr := os.ReadFile(m.rtcWakePath); readErr == nil {
		trimmed := strings.TrimSpace(string(data))
		if epoch, convErr := strconv.ParseInt(trimmed, 10, 64); convErr == nil && epoch > 0 {
			rep.HardwareRTCAlarm = time.Unix(epoch, 0).Format("2006-01-02 15:04:05") + " (armed)"
		}
	}

	if _, lookErr := m.lookPath("systemctl"); lookErr == nil {
		if monOut, mErr := m.exec.RunWithInput(ctx, security.RunOptions{Timeout: 5 * time.Second}, "systemctl", "--user", "is-active", UnitMonitorService); mErr == nil {
			if s := strings.TrimSpace(monOut); s != "" {
				rep.MonitorServiceStatus = s
			}
		}
		if tmrOut, tErr := m.exec.RunWithInput(ctx, security.RunOptions{Timeout: 5 * time.Second}, "systemctl", "--user", "is-active", UnitWakeupTimer); tErr == nil {
			if s := strings.TrimSpace(tmrOut); s != "" && s != "inactive" && s != "failed" {
				rep.WakeupTimerStatus = s
			}
		}
		if rep.WakeupTimerStatus == "inactive" {
			if tmrOut, tErr := m.exec.RunWithInput(ctx, security.RunOptions{Timeout: 5 * time.Second}, "systemctl", "--user", "is-active", "aitools-wake.timer"); tErr == nil {
				if s := strings.TrimSpace(tmrOut); s != "" {
					rep.WakeupTimerStatus = s
				}
			}
		}
	}

	if recent, logErr := m.store.TailLog(1); logErr == nil && len(recent) > 0 {
		rep.LastAuditEvent = recent[0]
	}

	return rep, nil
}

// FormatStatus renders a human-readable summary of StatusReport.
func FormatStatus(rep *StatusReport) string {
	var sb strings.Builder
	sb.WriteString("ANX AI Daemon & Hardware RTC Auto-Wake Status:\n")
	fmt.Fprintf(&sb, "  Auto-Wake Enabled:  %v\n", rep.AutoWakeEnabled)
	fmt.Fprintf(&sb, "  Target Wake Time:   %s\n", rep.TargetWakeTime)
	fmt.Fprintf(&sb, "  Auto-Resuspend:     %v (delay: %ds)\n", rep.AutoResuspend, rep.ResuspendDelaySec)
	if !rep.NextScheduledWake.IsZero() {
		fmt.Fprintf(&sb, "  Next Scheduled RTC: %s\n", rep.NextScheduledWake.Format("2006-01-02 15:04:05"))
	}
	fmt.Fprintf(&sb, "  Hardware Alarm:     %s\n", rep.HardwareRTCAlarm)
	fmt.Fprintf(&sb, "  Monitor Service:    %s\n", rep.MonitorServiceStatus)
	fmt.Fprintf(&sb, "  Wakeup Timer:       %s\n", rep.WakeupTimerStatus)
	fmt.Fprintf(&sb, "  Audit Log:          %s\n", rep.AuditLogPath)
	if rep.LastAuditEvent != "" {
		fmt.Fprintf(&sb, "  Last Log Event:     %s\n", rep.LastAuditEvent)
	}
	return strings.TrimRight(sb.String(), "\n")
}

// RunWakeCycle executes the scheduled wake cycle:
//  1. Verifies network reconnect
//  2. Executes target wakeup probes
//  3. Validates 100% probe success (aborts suspend on any failure guardrail!)
//  4. Re-arms next day's RTC alarm
//  5. Sends desktop & Telegram notifications and triggers cross-platform safe suspend.
func (m *Manager) RunWakeCycle(ctx context.Context, out io.Writer) (*WakeCycleResult, error) {
	if out == nil {
		out = io.Discard
	}

	st, err := m.store.Load()
	if err != nil {
		return nil, err
	}

	nowEpoch := m.nowFunc().Unix()
	if st.LastAutoWakeEpoch > 0 && nowEpoch-st.LastAutoWakeEpoch < 300 && nowEpoch >= st.LastAutoWakeEpoch {
		fmt.Fprintf(out, "Wake cycle already executed %ds ago; skipping duplicate trigger.\n", nowEpoch-st.LastAutoWakeEpoch)
		return &WakeCycleResult{}, nil
	}

	st.LastAutoWakeEpoch = nowEpoch
	st.ExpectingAutoWake = false
	if err := m.store.Save(st); err != nil {
		return nil, err
	}

	res := &WakeCycleResult{}
	aw := m.cfg.Daemon.AutoWake
	_ = m.store.AppendLog("INFO", "TIMER_WAKE_START", "Executing scheduled wake cycle", nil)
	fmt.Fprintln(out, "==> anx ai: Executing scheduled wake cycle...")

	// 1. Verify network reconnect
	fmt.Fprintf(out, "Awaiting network connectivity (timeout %s)...\n", m.connectivity.Timeout)
	if netErr := WaitForConnectivityWithOptions(ctx, m.connectivity); netErr != nil {
		res.AbortReason = "network connectivity timeout"
		msg := "Internet connectivity unavailable after wakeup."
		fmt.Fprintln(out, msg)
		_ = m.store.AppendLog("ERROR", "NETWORK_TIMEOUT", msg, nil)
		m.Notify(ctx, "ANX AI: Wakeup Failed", msg, "critical")
		if aw.Enabled {
			_, _, _ = m.ScheduleNextRTC(ctx, aw.Time)
		}
		if aw.AutoResuspend {
			delay := time.Duration(aw.ResuspendDelaySec) * time.Second
			if delay < 0 {
				delay = 0
			}
			msgSuspend := fmt.Sprintf("Network unavailable; resuspending in %ds...", aw.ResuspendDelaySec)
			fmt.Fprintln(out, msgSuspend)
			_ = m.store.AppendLog("INFO", "SUSPEND_PENDING", msgSuspend, nil)
			_ = m.sleepDelay(ctx, delay)
			method, susErr := m.SafeSuspend(ctx)
			if susErr != nil {
				_ = m.store.AppendLog("ERROR", "SUSPEND_FAILED", susErr.Error(), nil)
				return res, fmt.Errorf("safe suspend after network timeout failed: %w", susErr)
			}
			res.Suspended = true
			res.SuspendMethod = method
			_ = m.store.AppendLog("INFO", "SUSPEND_SUCCESS", "Suspended via "+method, nil)
		} else {
			res.AbortedSuspend = true
		}
		return res, fmt.Errorf("wake cycle network guardrail: %w", netErr)
	}

	res.NetworkVerified = true
	_ = m.store.AppendLog("INFO", "NETWORK_OK", "Internet connectivity and DNS verified", nil)

	// 2. Execute wakeup probes and validate probe success
	wakeRep, wakeErr := m.quotaSvc.WakeWithOptions(ctx, quota.WakeOptions{
		Force:  true,
		Reason: "scheduled_wake_cycle",
		Out:    out,
	})
	res.WakeReport = wakeRep

	if wakeErr != nil || (wakeRep != nil && !wakeRep.AllSucceeded()) {
		res.AbortReason = "target wakeup probe failure"
		msg := "One or more model wakeup probes failed."
		fmt.Fprintln(out, msg)
		_ = m.store.AppendLog("ERROR", "WAKE_FAILED", msg, nil)
		m.Notify(ctx, "ANX AI: Wakeup Failed", msg, "critical")
		if aw.Enabled {
			_, _, _ = m.ScheduleNextRTC(ctx, aw.Time)
		}
		if wakeErr == nil {
			wakeErr = errors.New("wakeup probe reported target failures")
		}
		if aw.AutoResuspend {
			delay := time.Duration(aw.ResuspendDelaySec) * time.Second
			if delay < 0 {
				delay = 0
			}
			msgSuspend := fmt.Sprintf("Wake probes failed; resuspending in %ds...", aw.ResuspendDelaySec)
			fmt.Fprintln(out, msgSuspend)
			_ = m.store.AppendLog("INFO", "SUSPEND_PENDING", msgSuspend, nil)
			_ = m.sleepDelay(ctx, delay)
			method, susErr := m.SafeSuspend(ctx)
			if susErr != nil {
				_ = m.store.AppendLog("ERROR", "SUSPEND_FAILED", susErr.Error(), nil)
				return res, fmt.Errorf("safe suspend after probe failure failed: %w", susErr)
			}
			res.Suspended = true
			res.SuspendMethod = method
			_ = m.store.AppendLog("INFO", "SUSPEND_SUCCESS", "Suspended via "+method, nil)
		} else {
			res.AbortedSuspend = true
		}
		return res, fmt.Errorf("wake cycle probe guardrail: %w", wakeErr)
	}

	// 3. Re-arm next day's RTC alarm
	if aw.Enabled {
		_, _, _ = m.ScheduleNextRTC(ctx, aw.Time)
	}

	// 4. Trigger cross-platform safe suspend ONLY after full verified probe success
	if aw.AutoResuspend {
		delay := time.Duration(aw.ResuspendDelaySec) * time.Second
		if delay < 0 {
			delay = 0
		}
		msg := fmt.Sprintf("Model quotas primed. Resuspending in %ds...", aw.ResuspendDelaySec)
		fmt.Fprintln(out, msg)
		_ = m.store.AppendLog("INFO", "SUSPEND_PENDING", msg, nil)
		m.Notify(ctx, "ANX AI: Wake Complete", msg, "normal")

		if err := m.sleepDelay(ctx, delay); err != nil {
			return res, err
		}

		method, susErr := m.SafeSuspend(ctx)
		if susErr != nil {
			_ = m.store.AppendLog("ERROR", "SUSPEND_FAILED", susErr.Error(), nil)
			return res, fmt.Errorf("safe suspend failed: %w", susErr)
		}
		res.Suspended = true
		res.SuspendMethod = method
		_ = m.store.AppendLog("INFO", "SUSPEND_SUCCESS", "Suspended via "+method, nil)
	} else {
		m.Notify(ctx, "ANX AI: Wake Complete", "Model rolling quota windows successfully primed.", "normal")
	}

	return res, nil
}

// SafeSuspend suspends the host operating system safely across Linux, macOS, and Windows.
func (m *Manager) SafeSuspend(ctx context.Context) (string, error) {
	if m.suspendOverride != nil {
		return m.suspendOverride(ctx)
	}

	switch m.plat.OS() {
	case "linux":
		if _, err := m.lookPath("systemctl"); err == nil {
			if _, rErr := m.exec.RunWithInput(ctx, security.RunOptions{Timeout: 10 * time.Second}, "systemctl", "--no-ask-password", "suspend"); rErr == nil {
				return "systemctl suspend", nil
			}
			if _, rErr := m.exec.RunWithInput(ctx, security.RunOptions{Timeout: 10 * time.Second}, "sudo", "-n", "systemctl", "--no-ask-password", "suspend"); rErr == nil {
				return "sudo systemctl suspend", nil
			}
		}
		if _, err := m.lookPath("loginctl"); err == nil {
			if _, rErr := m.exec.RunWithInput(ctx, security.RunOptions{Timeout: 10 * time.Second}, "loginctl", "--no-ask-password", "suspend"); rErr == nil {
				return "loginctl suspend", nil
			}
			if _, rErr := m.exec.RunWithInput(ctx, security.RunOptions{Timeout: 10 * time.Second}, "sudo", "-n", "loginctl", "--no-ask-password", "suspend"); rErr == nil {
				return "sudo loginctl suspend", nil
			}
		}
		if _, err := m.lookPath("pm-suspend"); err == nil {
			if _, rErr := m.exec.RunWithInput(ctx, security.RunOptions{Timeout: 10 * time.Second}, "sudo", "-n", "pm-suspend"); rErr == nil {
				return "pm-suspend", nil
			}
		}
		return "", errors.New("all Linux suspend commands (systemctl, loginctl, pm-suspend) failed")

	case "darwin":
		if _, err := m.lookPath("pmset"); err == nil {
			if _, rErr := m.exec.RunWithInput(ctx, security.RunOptions{Timeout: 10 * time.Second}, "pmset", "sleepnow"); rErr == nil {
				return "pmset sleepnow", nil
			}
		}
		if _, err := m.lookPath("osascript"); err == nil {
			if _, rErr := m.exec.RunWithInput(ctx, security.RunOptions{Timeout: 10 * time.Second}, "osascript", "-e", `tell application "System Events" to sleep`); rErr == nil {
				return "osascript sleep", nil
			}
		}
		return "", errors.New("macOS sleep commands (pmset, osascript) failed")

	case "windows":
		if _, err := m.lookPath("rundll32.exe"); err == nil {
			if _, rErr := m.exec.RunWithInput(ctx, security.RunOptions{Timeout: 10 * time.Second}, "rundll32.exe", "powrprof.dll,SetSuspendState", "0,1,0"); rErr == nil {
				return "rundll32 powrprof.dll,SetSuspendState", nil
			}
		}
		if _, err := m.lookPath("rundll32"); err == nil {
			if _, rErr := m.exec.RunWithInput(ctx, security.RunOptions{Timeout: 10 * time.Second}, "rundll32", "powrprof.dll,SetSuspendState", "0,1,0"); rErr == nil {
				return "rundll32 powrprof.dll,SetSuspendState", nil
			}
		}
		return "", errors.New("Windows SetSuspendState suspend failed")

	default:
		return "", fmt.Errorf("unsupported OS %q for system suspend", m.plat.OS())
	}
}

// Notify dispatches desktop banners (notify-send / osascript) and optional Telegram Bot webhooks.
func (m *Manager) Notify(ctx context.Context, title, body, urgency string) {
	if urgency == "" {
		urgency = "normal"
	}

	if m.cfg.Daemon.DesktopNotifications || m.cfg.Notifications.Desktop {
		switch m.plat.OS() {
		case "darwin":
			if _, err := m.lookPath("osascript"); err == nil {
				safeBody := strings.ReplaceAll(body, `"`, `'`)
				safeTitle := strings.ReplaceAll(title, `"`, `'`)
				script := fmt.Sprintf(`display notification "%s" with title "%s"`, safeBody, safeTitle)
				_, _ = m.exec.RunWithInput(ctx, security.RunOptions{Timeout: 5 * time.Second}, "osascript", "-e", script)
			}
		default:
			if _, err := m.lookPath("notify-send"); err == nil {
				_, _ = m.exec.RunWithInput(
					ctx,
					security.RunOptions{Timeout: 5 * time.Second},
					"notify-send",
					"-u",
					urgency,
					"-a",
					"anx-ai",
					"-i",
					"utilities-terminal",
					title,
					body,
				)
			}
		}
	}

	tg := m.cfg.Daemon.Telegram
	token := strings.TrimSpace(tg.BotToken)
	if token == "" {
		token = strings.TrimSpace(os.Getenv("TELEGRAM_BOT_TOKEN"))
	}
	chatID := strings.TrimSpace(tg.ChatID)
	if chatID == "" {
		chatID = strings.TrimSpace(os.Getenv("TELEGRAM_CHAT_ID"))
	}

	if (tg.Enabled || token != "") && token != "" && chatID != "" {
		endpoint := fmt.Sprintf("%s/bot%s/sendMessage", m.telegramAPIURL, token)
		form := url.Values{}
		form.Set("chat_id", chatID)
		form.Set("text", fmt.Sprintf("*%s*\n%s", title, body))
		form.Set("parse_mode", "Markdown")

		reqCtx, cancel := context.WithTimeout(ctx, 5*time.Second)
		defer cancel()

		req, err := http.NewRequestWithContext(reqCtx, http.MethodPost, endpoint, strings.NewReader(form.Encode()))
		if err == nil {
			req.Header.Set("Content-Type", "application/x-www-form-urlencoded")
			if resp, doErr := m.httpClient.Do(req); doErr == nil {
				_, _ = io.Copy(io.Discard, resp.Body)
				_ = resp.Body.Close()
			}
		}
	}
}

// RunMonitor listens to D-Bus PrepareForSleep signals and arms hardware RTC wakeups before sleep.
func (m *Manager) RunMonitor(ctx context.Context, out io.Writer) error {
	if out == nil {
		out = io.Discard
	}
	if m.cfg.Daemon.AutoWake.Enabled {
		_, _, _ = m.ScheduleNextRTC(ctx, m.cfg.Daemon.AutoWake.Time)
	}

	gdbusPath, err := m.lookPath("gdbus")
	if err != nil {
		return errors.New("gdbus executable not found in PATH; D-Bus sleep/resume monitor requires gdbus")
	}

	cmd := exec.CommandContext(ctx, gdbusPath, "monitor", "--system", "--dest", "org.freedesktop.login1")
	stdout, err := cmd.StdoutPipe()
	if err != nil {
		return fmt.Errorf("opening gdbus stdout pipe: %w", err)
	}
	if err := cmd.Start(); err != nil {
		return fmt.Errorf("starting gdbus monitor: %w", err)
	}

	fmt.Fprintln(out, "==> anx ai D-Bus sleep/resume monitor active...")
	scanner := bufio.NewScanner(stdout)
	for scanner.Scan() {
		if ctx.Err() != nil {
			break
		}
		_ = m.HandleDBusLine(ctx, out, scanner.Text())
	}

	_ = cmd.Wait()
	if errors.Is(ctx.Err(), context.Canceled) {
		return nil
	}
	return scanner.Err()
}

// HandleDBusLine processes a single gdbus monitor line for PrepareForSleep transitions.
func (m *Manager) HandleDBusLine(ctx context.Context, out io.Writer, line string) error {
	if out == nil {
		out = io.Discard
	}
	if strings.Contains(line, "PrepareForSleep: <true>") {
		if m.cfg.Daemon.AutoWake.Enabled {
			t, _, err := m.ScheduleNextRTC(ctx, m.cfg.Daemon.AutoWake.Time)
			fmt.Fprintf(out, "[D-Bus] Pre-sleep: RTC alarm scheduled for %s\n", t.Format("2006-01-02 15:04:05"))
			return err
		}
		return nil
	}

	if strings.Contains(line, "PrepareForSleep: <false>") {
		st, err := m.store.Load()
		if err != nil {
			return err
		}
		now := m.nowFunc().Unix()
		maxWindowSec := int64(m.cfg.Daemon.AutoWake.MaxWakeWindowMinutes * 60)
		if maxWindowSec <= 0 {
			maxWindowSec = 15 * 60
		}

		if st.ExpectingAutoWake && st.ScheduledWakeEpoch > 0 && now >= st.ScheduledWakeEpoch {
			if now-st.ScheduledWakeEpoch > maxWindowSec {
				_ = m.store.AppendLog("WARN", "MISSED_WAKE_CATCHUP", fmt.Sprintf("Scheduled wake passed %ds ago during sleep; running catchup wake cycle now", now-st.ScheduledWakeEpoch), nil)
				fmt.Fprintf(out, "[D-Bus] Missed scheduled wake during sleep (%ds late); executing catchup wake cycle...\n", now-st.ScheduledWakeEpoch)
			} else {
				fmt.Fprintln(out, "[D-Bus] On-schedule resume detected; executing wake cycle...")
			}
			_, err := m.RunWakeCycle(ctx, out)
			return err
		}

		_ = m.store.AppendLog("INFO", "USER_RESUME", "Manual user resume detected", nil)
		if m.cfg.Daemon.AutoWake.Enabled && (!st.ExpectingAutoWake || now >= st.ScheduledWakeEpoch) {
			_, _, _ = m.ScheduleNextRTC(ctx, m.cfg.Daemon.AutoWake.Time)
		}
	}
	return nil
}

// Logs returns the most recent lines from daemon.log.
