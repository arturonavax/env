package operation

import (
	"bytes"
	"encoding/base64"
	"fmt"
	"strings"
)

// UnsupportedOperationError reports that a specific operation cannot be rendered by the target shell.
type UnsupportedOperationError struct {
	OpID   string
	Kind   OperationKind
	Target string
	Reason string
}

func (e *UnsupportedOperationError) Error() string {
	return fmt.Sprintf("unsupported operation %s (kind %s) for target %s: %s", e.OpID, e.Kind, e.Target, e.Reason)
}

// RenderOptions configures deterministic rendering behavior.
type RenderOptions struct {
	Deterministic bool
	Standalone    bool
	IncludeHeader bool
	TargetShell   string // "sh", "bash", "powershell"
}

// Renderer compiles an immutable PlanIR into an executable shell script.
type Renderer interface {
	Target() string
	CanRender(op Operation) bool
	Render(plan PlanIR, opts RenderOptions) ([]byte, error)
}

// ShRenderer generates pure POSIX /bin/sh compatible scripts.
type ShRenderer struct{}

func (r *ShRenderer) Target() string {
	return "sh"
}

func (r *ShRenderer) CanRender(op Operation) bool {
	switch op.Kind {
	case OpExecArgv, OpEnsureDirectory, OpCopyAtomic, OpWriteAtomic, OpDeleteOwned, OpCreateSymlinkOwned, OpPackageInstall, OpPackageRemove, OpPackageUpgrade:
		return true
	case OpAnxRuntimeDelegation:
		return true
	default:
		return false
	}
}

func (r *ShRenderer) Render(plan PlanIR, opts RenderOptions) ([]byte, error) {
	var buf bytes.Buffer

	if opts.IncludeHeader {
		buf.WriteString("#!/bin/sh\n")
		buf.WriteString("# ==============================================================================\n")
		buf.WriteString("# Generated by ANX Operation IR Compiler (POSIX sh target)\n")
		if !opts.Deterministic {
			buf.WriteString(fmt.Sprintf("# Plan ID: %s\n", plan.ID))
		}
		buf.WriteString("# Mode: set -eu (Defensive POSIX)\n")
		buf.WriteString("# ==============================================================================\n")
		buf.WriteString("set -eu\n\n")
	}

	for _, op := range plan.Operations {
		if !r.CanRender(op) {
			return nil, &UnsupportedOperationError{
				OpID:   op.OpID,
				Kind:   op.Kind,
				Target: "sh",
				Reason: "requires complex runtime capability not expressible in standalone POSIX sh",
			}
		}

		if op.Description != "" {
			buf.WriteString(fmt.Sprintf("# [%s] %s\n", op.OpID, op.Description))
		}

		line, err := renderPOSIXOp(op, opts)
		if err != nil {
			return nil, err
		}
		buf.WriteString(line)
		buf.WriteString("\n\n")
	}

	buf.WriteString("echo \"All planned operations completed successfully.\"\n")
	return buf.Bytes(), nil
}

