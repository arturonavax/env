// StatusReport holds runtime diagnostics for the background daemon and hardware RTC alarm.
type StatusReport struct {
	AutoWakeEnabled      bool      `json:"auto_wake_enabled"`
	TargetWakeTime       string    `json:"target_wake_time"`
	AutoResuspend        bool      `json:"auto_resuspend"`
	ResuspendDelaySec    int       `json:"resuspend_delay_seconds"`
	NextScheduledWake    time.Time `json:"next_scheduled_wake,omitempty"`
	HardwareRTCAlarm     string    `json:"hardware_rtc_alarm"`
	MonitorServiceStatus string    `json:"monitor_service_status"`
	WakeupTimerStatus    string    `json:"wakeup_timer_status"`
	AuditLogPath         string    `json:"audit_log_path"`
	LastAuditEvent       string    `json:"last_audit_event,omitempty"`
}

// InstallResult lists unit or plist files generated by Manager.Install.
type InstallResult struct {
	Files []string `json:"files"`
}

// WakeCycleResult reports the execution outcome of RunWakeCycle.
type WakeCycleResult struct {
	NetworkVerified bool              `json:"network_verified"`
	WakeReport      *quota.WakeReport `json:"wake_report,omitempty"`
	Suspended       bool              `json:"suspended"`
	SuspendMethod   string            `json:"suspend_method,omitempty"`
	AbortedSuspend  bool              `json:"aborted_suspend"`
	AbortReason     string            `json:"abort_reason,omitempty"`
}

// CommandExecutor abstracts external command execution for testability.
type CommandExecutor interface {
	RunWithInput(ctx context.Context, opts security.RunOptions, binary string, args ...string) (string, error)
}

// Manager supervises systemd/launchd installation, RTC wakeup alarms, network probes, notifications, and safe suspend.
type Manager struct {
	cfg             *config.Config
	configPath      string
	store           *config.StateStore
	quotaSvc        *quota.Service
	plat            *platform.Info
	exec            CommandExecutor
	lookPath        func(string) (string, error)
	connectivity    ConnectivityOptions
	httpClient      *http.Client
	binaryPath      string
	rtcWakePath     string
	telegramAPIURL  string
	nowFunc         func() time.Time
	sleepDelay      func(context.Context, time.Duration) error
	suspendOverride func(context.Context) (string, error)
}

// ManagerOption customizes a daemon Manager.
type ManagerOption func(*Manager)

