// NewManager constructs a daemon Manager.
func NewManager(
	cfg *config.Config,
	store *config.StateStore,
	quotaSvc *quota.Service,
	opts ...ManagerOption,
) *Manager {
	if cfg == nil {
		cfg, _ = config.DefaultConfig()
	}
	if store == nil {
		store = config.NewStateStore("")
	}
	plat := platform.Detect()
	if quotaSvc == nil {
		quotaSvc = quota.NewService(cfg, store)
	}

	transport := &http.Transport{
		MaxIdleConns:        4,
		MaxIdleConnsPerHost: 2,
		IdleConnTimeout:     30 * time.Second,
	}

	m := &Manager{
		cfg:            cfg,
		configPath:     config.DefaultConfigPath(plat.HomeDir()),
		store:          store,
		quotaSvc:       quotaSvc,
		plat:           plat,
		exec:           security.NewRunner(20 * time.Second),
		lookPath:       exec.LookPath,
		connectivity:   DefaultConnectivityOptions(120 * time.Second),
		httpClient:     &http.Client{Timeout: 5 * time.Second, Transport: transport},
		rtcWakePath:    "/sys/class/rtc/rtc0/wakealarm",
		telegramAPIURL: "https://api.telegram.org",
		nowFunc:        time.Now,
		sleepDelay:     defaultSleepDelay,
	}
	for _, opt := range opts {
		opt(m)
	}
	if m.binaryPath == "" {
		m.binaryPath = filepath.Join(m.plat.LocalBinDir(), "anx")
	}
	return m
}

func defaultSleepDelay(ctx context.Context, d time.Duration) error {
	if d <= 0 {
		return nil
	}
	t := time.NewTimer(d)
	defer t.Stop()
	select {
	case <-ctx.Done():
		return ctx.Err()
	case <-t.C:
		return nil
	}
}

